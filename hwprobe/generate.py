"""Hardware probes for the hazard rules of `radisa check` (gfx1201 / RDNA4, wave32).

For every hazard class this emits one self-contained HIP file with two kernels that differ only
in the wait / separation the rule asks for:

* `<case>_hazard`: the wait, nop or VALU is missing; `radisa check` reports `expect_rule` on it.
* `<case>_fixed`:  the form LLVM's AMDGPU backend emits (or the wait the rule asks for);
  `radisa check` reports no error on it.

Both compute the same host-predicted result (`expected()` below, written by `--data`). A mismatch
on `_hazard` is hardware evidence for the rule; a mismatch on `_fixed` is a harness bug (or, for
`d16_other_half`, evidence against the relaxation the linter takes from LLVM). Races depend on
timing: zero mismatches on `_hazard` does NOT show that a rule is unnecessary.

Run on hardware once: one Radeon AI PRO R9700, 2026-11-12, cases as of commit 1fe68fb, AMD clang 24
(ROCm d6f6cb69), 200 launches per variant, grid 512 (`HARDWARE_RUNS`, hwprobe/README.md). Not re-run
since; not run on a second GPU.

    python3 hwprobe/generate.py                  # rewrite hwprobe/cases/*.hip + manifest.json
    python3 hwprobe/generate.py --check          # exit 1 if the checked-in files are stale
    python3 hwprobe/generate.py --data DIR       # inputs, expected outputs, cases.tsv for host_runner
    python3 hwprobe/generate.py --verify-lint DIR  # exit 1 unless DIR/<case>.json match the manifest

Every kernel: `(unsigned *out, const unsigned *in)`, block 256 (8 waves of 32), one input word per
thread, `words_per_lane` output words per thread; `out` is filled with `fill_byte` before each launch.
"""
