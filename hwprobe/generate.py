def _neighbour(i: int) -> int:
    """Thread of the same workgroup one wave further on: its LDS word is written by another wave."""
    return (i & ~(BLOCK - 1)) | ((i + WAVE) & (BLOCK - 1))


def _carry_add(i: int, x: int) -> tuple[int, int]:
    s = x + 0x80000000
    return s & 0xFFFFFFFF, (i + (s >> 32)) & 0xFFFFFFFF


def _perm(i: int, inp: list[int]) -> int:
    lane = i % WAVE
    return inp[(i - lane) + 15 - lane] if lane < 16 else PERM_SENTINEL


