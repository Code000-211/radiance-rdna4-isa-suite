def _wmma_fill() -> dict:
    """Register set-up of the WMMA probe: A1 = 0, B = f16 1.0, C1 = 0x3c003c00, D1/D2 start at 0."""
    def mov(lo, hi, val):
        return ''.join(f'"v_mov_b32 v{r}, {val}\\n\\t"\n      ' for r in range(lo, hi + 1))
    return dict(zero_a=mov(64, 67, 0), ones_b=mov(68, 71, '0x3c003c00'), c_init=mov(88, 95, '0x3c003c00'),
                d_init=mov(72, 79, 0), d2_init=mov(80, 87, 0),
                clobbers=', '.join(f'"v{r}"' for r in range(64, 96)))


def kernel_source(case: dict, variant: str) -> str:
    """The C++ text of one kernel."""
    nl = '\n      '                    # one asm string per line in the generated source
    snippet = case['variants'][variant]
    fields = dict(ids=IDS.format(words=case['words']), lds_base=LDS_BASE, variant=snippet + nl if snippet else '', dsnop=DSNOP4 + nl,
                  dsnop_end=DSNOP4[:-5] + '"')
    if case['name'] == 'wmma_d_to_a':
        fields.update(_wmma_fill())
    body = case['body'].format(**fields)
    body = body.replace('\n      \n', '\n')
    return f'HWPROBE_KERNEL {case["name"]}_{variant}(u32 *out, const u32 *in) {{\n{body}}}\n'


def hip_source(case: dict) -> str:
    head = HEADER.format(**{k: case[k] for k in ('name', 'title', 'rule', 'basis', 'hazard_note', 'fixed_note')})
    return head + '\n' + '\n'.join(kernel_source(case, v) for v in ('hazard', 'fixed'))


def manifest() -> dict:
    """What run_probes.sh / host_runner and tests/test_hwprobe.py need, per case."""
    return {
        'schema': 'radisa-hwprobe-1',
        'target': 'gfx1201',
        'wave': WAVE,
        'block': BLOCK,
        'grid': GRID,
        'iterations': ITERATIONS,
        'fill_byte': FILL_BYTE,
        'hardware_runs': HARDWARE_RUNS,
        'note': 'A mismatch on a hazard variant is evidence for the rule; zero '
                'mismatches do not show the rule is unnecessary. A mismatch on a fixed variant is a harness bug.',
        'cases': [{
            'name': c['name'],
            'file': f'cases/{c["name"]}.hip',
            'title': c['title'],
            'basis': c['basis'],
            'words_per_lane': c['words'],
            'variants': {
                'hazard': {'kernel': f'{c["name"]}_hazard', 'expect': c['rule'],
                           'severity': 'review' if c['rule'] in REVIEW_RULES else 'error', 'note': c['hazard_note']},
                'fixed': {'kernel': f'{c["name"]}_fixed', 'expect': 'clean', 'note': c['fixed_note']},
            },
        } for c in CASES],
    }


def sources() -> dict[str, str]:
    """File name (relative to hwprobe/cases) -> text, for every generated file."""
    out = {f'{c["name"]}.hip': hip_source(c) for c in CASES}
    out['manifest.json'] = json.dumps(manifest(), indent=2, sort_keys=True) + '\n'
    return out


def inputs(case: dict, grid: int = GRID) -> list[int]:
    """Deterministic input words (a 32-bit LCG seeded by the case name)."""
    x = sum(case['name'].encode()) * 2654435761 & 0xFFFFFFFF
    out = []
    for _ in range(grid * BLOCK):
        x = (x * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append(x)
    return out


def expected(case: dict, inp: list[int]) -> list[int]:
    """The output words the kernel must produce (both variants), computed on the host."""
    words = []
    for i, x in enumerate(inp):
        r = case['expected'](i, x, inp)
        words.extend(r if isinstance(r, tuple) else (r,))
    assert len(words) == len(inp) * case['words']
    return words


def write_data(out_dir: Path, hsaco_dir: str = '.', grid: int = GRID) -> Path:
    """<case>.in.bin, <case>.expect.bin (little-endian u32) and cases.tsv, the host runner's input."""
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for c in CASES:
        inp = inputs(c, grid)
        exp = expected(c, inp)
        (out_dir / f'{c["name"]}.in.bin').write_bytes(struct.pack(f'<{len(inp)}I', *inp))
        (out_dir / f'{c["name"]}.expect.bin').write_bytes(struct.pack(f'<{len(exp)}I', *exp))
        for v in ('hazard', 'fixed'):
            rows.append('\t'.join(map(str, (
                c['name'], v, f'{c["name"]}_{v}', f'{hsaco_dir}/{c["name"]}.hsaco', grid, BLOCK,
                out_dir / f'{c["name"]}.in.bin', out_dir / f'{c["name"]}.expect.bin',
                len(exp), FILL_BYTE, c['rule'] if v == 'hazard' else 'clean'))))
    tsv = out_dir / 'cases.tsv'
    tsv.write_text('# case\tvariant\tkernel\thsaco\tgrid\tblock\tin\texpect\tout_words\tfill_byte\texpect_rule\n'
                   + '\n'.join(rows) + '\n')
    return tsv


